// Writes ../DawnTools_Seed/Dungeons.lua (the seed addon beside DawnTools; in no download and no repository, see
// Core/DBSeed.lua): every dungeon with its levels, its bosses in order, and what each drops.
//   node tools/dungeons.js ["<...>/Interface/AddOns/OneForAll"]     (default: the addon folder next to this one)
// Read from the OneForAll addon (GPL-3.0-or-later, see THIRD_PARTY_LICENSES.txt): its Data/Dungeons/*.lua (the
// bosses and their loot) and Data/DungeonDropChance.lua (drop chances). Taken: dungeon and boss names, NPC and
// item numbers, level ranges, drop chances. Not taken: its descriptions, notes, quests, maps.
// Needs the test suite's packages: cd tests && npm install
const fs = require('fs');
const path = require('path');
const { lua, lauxlib, lualib, to_luastring, to_jsstring } = require('../tests/node_modules/fengari');

const src = path.resolve(process.argv[2] || path.join(__dirname, '..', '..', 'OneForAll'));
const out = path.resolve(__dirname, '..', '..', 'DawnTools_Seed', 'Dungeons.lua');
const version = (fs.readFileSync(path.join(src, 'OneForAll.toc'), 'utf8').match(/## Version:\s*(\S+)/) || [])[1] || '?';
const files = fs.readdirSync(path.join(src, 'Data', 'Dungeons')).filter(f => f.endsWith('.lua')).sort();

const MAKE = `
local src, version, names = ...
local FLT = { DUNGEON_REGISTRY = {} }
for file in names:gmatch("[^\\n]+") do
	assert(loadfile(src .. "/Data/Dungeons/" .. file))("OneForAll", FLT)
end
assert(loadfile(src .. "/Data/DungeonDropChance.lua"))("OneForAll", FLT)
local chances = FLT.DUNGEON_DROP_CHANCE or {}
local function Q(s) return ("%q"):format(s):gsub("\\\\\\n", "\\\\n") end
local list = {}
for name, d in pairs(FLT.DUNGEON_REGISTRY) do
	local lo, hi = tostring(d.level or ""):match("(%d+)%D+(%d+)")
	if not lo then lo = tostring(d.level or ""):match("(%d+)") hi = lo end
	list[#list + 1] = { name = name, lo = tonumber(lo) or 0, hi = tonumber(hi) or 0, d = d }
end
table.sort(list, function(a, b)
	if a.lo ~= b.lo then return a.lo < b.lo end
	return a.name < b.name
end)
local lines = {
	"-- Every dungeon: { name, lowest level, highest level, { boss, ... } }, a boss being",
	"-- { name, NPC (0: not known), rare (1) or not (0), { item, chance in a hundred (0: not known), item, chance, ... } }.",
	"-- The last \\"boss\\" of a dungeon, where there is one, is \\"Trash\\": what its other mobs drop.",
	"-- GENERATED by tools/dungeons.js: do not edit by hand.",
	"-- Source: OneForAll " .. version .. " by Smoergi, GPL-3.0-or-later: its Data/Dungeons/*.lua and",
	"-- Data/DungeonDropChance.lua. See THIRD_PARTY_LICENSES.txt.",
	"local _, DT = ...",
	"DT.OneForAllVersion = " .. ("%q"):format(version),
	"DT.Dungeons = {",
}
local bosses, items = 0, 0
for _, e in ipairs(list) do
	local d, rows = e.d, {}
	local byBoss = chances[e.name] or {}
	local function Boss(name, npc, rare, loot)
		local flat, seen = {}, {}
		for _, it in ipairs(loot or {}) do
			local id = type(it) == "table" and tonumber(it[1])
			if id and id > 0 and not seen[id] then
				seen[id] = true
				local chance = tonumber((byBoss[name] or {})[id]) or 0
				flat[#flat + 1] = ("%d, %s"):format(id, ("%g"):format(chance))
				items = items + 1
			end
		end
		if flat[1] then
			rows[#rows + 1] = ("\\t\\t{ %s, %d, %d, { %s } },"):format(Q(name), tonumber(npc) or 0, rare and 1 or 0, table.concat(flat, ", "))
			bosses = bosses + 1
		end
	end
	for _, b in ipairs(d.bosses or {}) do
		if type(b) == "table" and type(b.name) == "string" then Boss(b.name, b.npcID, b.rare, b.loot) end
	end
	Boss("Trash", 0, false, d.trashLoot)
	if rows[1] then
		lines[#lines + 1] = ("\\t{ %s, %d, %d, {"):format(Q(e.name), e.lo, e.hi)
		for _, row in ipairs(rows) do lines[#lines + 1] = row end
		lines[#lines + 1] = "\\t} },"
	end
end
lines[#lines + 1] = "}"
return table.concat(lines, "\\n") .. "\\n", #list, bosses, items
`;

const L = lauxlib.luaL_newstate();
lualib.luaL_openlibs(L);
if (lauxlib.luaL_loadstring(L, to_luastring(MAKE)) !== lua.LUA_OK) throw new Error(to_jsstring(lua.lua_tostring(L, -1)));
lua.lua_pushstring(L, to_luastring(src.replace(/\\/g, '/')));
lua.lua_pushstring(L, to_luastring(version));
lua.lua_pushstring(L, to_luastring(files.join('\n')));
if (lua.lua_pcall(L, 3, 4, 0) !== lua.LUA_OK) throw new Error(to_jsstring(lua.lua_tostring(L, -1)));
fs.writeFileSync(out, to_jsstring(lua.lua_tostring(L, -4)));
console.log(`${lua.lua_tointeger(L, -3)} dungeons, ${lua.lua_tointeger(L, -2)} bosses, ${lua.lua_tointeger(L, -1)} drops written to ${out} (from OneForAll ${version})`);
