// Writes Data/CraftSkill.lua: for every item a profession makes, the profession and the skill band of its recipe.
//   node tools/craftskill.js ["<...>/Interface/AddOns/SkillUpForever"]     (default: the addon folder next to this one)
// Read from the SkillUp Forever addon (GPL-3.0-or-later, see THIRD_PARTY_LICENSES.txt): its Data/Recipes.lua
// (which item a recipe makes, and of which profession), Data/Thresholds.lua (orange, yellow, green, grey; which scroll
// teaches it) and Data/Trainer.lua (the skill a trainer asks). Item, profession and skill numbers only.
// Needs the test suite's packages: cd tests && npm install
const fs = require('fs');
const path = require('path');
const { lua, lauxlib, lualib, to_luastring, to_jsstring } = require('../tests/node_modules/fengari');

const src = path.resolve(process.argv[2] || path.join(__dirname, '..', '..', 'SkillUpForever'));
const out = path.resolve(__dirname, '..', 'Data', 'CraftSkill.lua');
const version = (fs.readFileSync(path.join(src, 'SkillUpForever.toc'), 'utf8').match(/## Version:\s*(\S+)/) || [])[1] || '?';

const MAKE = `
local src, version = ...
local ns = {}
for _, file in ipairs({ "Recipes", "Trainer", "Thresholds", "Vendor" }) do
	assert(loadfile(src .. "/Data/" .. file .. ".lua"))("SkillUpForever", ns)
end
local band, ids, unknown = {}, {}, 0
for spell, r in pairs(ns.RecipeData) do
	local item = type(r.output) == "table" and r.output.itemID
	local t = ns.Thresholds[spell]
	if item and t then
		-- learned at: what the trainer asks where a trainer teaches it; else the recipe's own least skill
		local learn = ns.TrainerFees[spell] and ns.TrainerFees[spell][2] or t[1]
		-- (a least skill of 1 on a recipe that stays yellow past 45 is the source's placeholder for "not known",
		-- not a recipe from the start: written as 0 rather than shown wrong)
		if learn == 1 and t[2] > 45 then learn, unknown = 0, unknown + 1 end
		-- (an item two recipes make: the one that is yellow soonest; the lower recipe number between equals)
		local was = band[item]
		if not was then ids[#ids + 1] = item end
		if not was or t[2] < was[3] or (t[2] == was[3] and spell < was.spell) then
			band[item] = { r.skillLine, learn, t[2], t[3], t[4], ns.RecipeScrolls[spell] and ns.RecipeScrolls[spell][1] or 0, spell = spell }
		end
	end
end
table.sort(ids)
local lines = {
	"-- For every item a profession makes: [item] = { profession (skill line), learned at, yellow, green, grey, scroll }.",
	"-- Scroll: the recipe item that teaches it; 0 = none (a trainer teaches it). Learned at 0: not known. Skill lines: 129 First Aid, 164 Blacksmithing, 165 Leatherworking, 171 Alchemy,",
	"-- 185 Cooking, 186 Mining, 197 Tailoring, 202 Engineering, 333 Enchanting.",
	"-- GENERATED by tools/craftskill.js: do not edit by hand.",
	"-- Source: SkillUp Forever " .. version .. " by cjber (https://github.com/cjber/skillup-forever), GPL-3.0-or-later:",
	"-- its Data/Recipes.lua and Data/Thresholds.lua (WoW: Forever client tables via wago.tools) and Data/Trainer.lua",
	"-- (CMaNGOS classic-db, GPL-3.0). See THIRD_PARTY_LICENSES.txt.",
	"local _, DT = ...",
	"DT.CraftSkill = {",
}
for _, item in ipairs(ids) do
	local b = band[item]
	lines[#lines + 1] = ("\\t[%d] = { %d, %d, %d, %d, %d, %d },"):format(item, b[1], b[2], b[3], b[4], b[5], b[6])
end
lines[#lines + 1] = "}"
-- what vendors ask for the reagents they sell
local sold = {}
for item in pairs(ns.VendorPrices) do sold[#sold + 1] = item end
table.sort(sold)
lines[#lines + 1] = ""
lines[#lines + 1] = "-- What a vendor asks for one of the reagents vendors sell: [item] = copper (before any discount)."
lines[#lines + 1] = "-- Source: the same addon's Data/Vendor.lua (which items: LibPeriodicTable-3.1, LGPL-2.1; prices: the client tables)."
lines[#lines + 1] = "DT.VendorPrice = {"
for _, item in ipairs(sold) do lines[#lines + 1] = ("\\t[%d] = %d,"):format(item, ns.VendorPrices[item]) end
lines[#lines + 1] = "}"
return table.concat(lines, "\\n") .. "\\n", #ids, unknown
`;

const L = lauxlib.luaL_newstate();
lualib.luaL_openlibs(L);
if (lauxlib.luaL_loadstring(L, to_luastring(MAKE)) !== lua.LUA_OK) throw new Error(to_jsstring(lua.lua_tostring(L, -1)));
lua.lua_pushstring(L, to_luastring(src.replace(/\\/g, '/')));
lua.lua_pushstring(L, to_luastring(version));
if (lua.lua_pcall(L, 2, 3, 0) !== lua.LUA_OK) throw new Error(to_jsstring(lua.lua_tostring(L, -1)));
fs.writeFileSync(out, to_jsstring(lua.lua_tostring(L, -3)));
console.log(`${lua.lua_tointeger(L, -2)} items (${lua.lua_tointeger(L, -1)} recipes with "learned at" not known) written to ${out} (from SkillUp Forever ${version})`);
