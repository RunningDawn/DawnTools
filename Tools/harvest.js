// Merges the quest rewards a player has seen into Data/QuestRewards.lua, which ships with the addon.
//   node tools/harvest.js "<...>/WTF/Account/<ACCOUNT>/SavedVariables/DawnTools.lua" [more saved files...]
// Only DawnToolsDB.quest.seen is read: quest numbers, money, experience, item numbers. Nothing about a player.
// Needs the test suite's packages: cd tests && npm install
const fs = require('fs');
const path = require('path');
const { lua, lauxlib, lualib, to_luastring, to_jsstring } = require('../tests/node_modules/fengari');

const out = path.resolve(__dirname, '..', 'Data', 'QuestRewards.lua');
const files = process.argv.slice(2);
if (!files.length) { console.error('usage: node tools/harvest.js <SavedVariables/DawnTools.lua> [...]'); process.exit(1); }

const MERGE = `
local out, files = ...
local all, was, new = {}, 0, 0
local function Take(list) -- { { item, count }, ... }, numbers only
	local t = {}
	for _, it in ipairs(type(list) == "table" and list or {}) do
		local id, n = tonumber(it[1]), tonumber(it[2]) or 1
		if id then t[#t + 1] = { math.floor(id), math.floor(n) } end
	end
	table.sort(t, function(a, b) return a[1] < b[1] end)
	return t
end
local function Add(id, rec)
	id = tonumber(id)
	if not id or type(rec) ~= "table" then return end
	if not all[id] then new = new + 1 end
	all[id] = { m = math.floor(tonumber(rec.m) or 0), x = math.floor(tonumber(rec.x) or 0), l = math.floor(tonumber(rec.l) or 0), r = Take(rec.r), c = Take(rec.c) }
end
-- what is shipped already
local DT = {}
local f = loadfile(out)
if f then f("DawnTools", DT) end
for id, rec in pairs(DT.QuestRewards or {}) do Add(id, rec) end
was, new = new, 0
-- what the saved files hold (a later sighting replaces an earlier one)
for path in files:gmatch("[^\\n]+") do
	local env = {}
	local saved, err = loadfile(path, "t", env)
	if not saved then error("cannot read " .. path .. ": " .. tostring(err)) end
	saved()
	local seen = env.DawnToolsDB and env.DawnToolsDB.quest and env.DawnToolsDB.quest.seen
	for id, rec in pairs(type(seen) == "table" and seen or {}) do Add(id, rec) end
end
local ids = {}
for id in pairs(all) do ids[#ids + 1] = id end
table.sort(ids)
local function Items(t)
	local s = {}
	for i, it in ipairs(t) do s[i] = "{" .. it[1] .. "," .. it[2] .. "}" end
	return "{" .. table.concat(s, ",") .. "}"
end
local lines = {}
for i, id in ipairs(ids) do
	local r = all[id]
	lines[i] = ("[%d]={m=%d,x=%d,l=%d,r=%s,c=%s},"):format(id, r.m, r.x, r.l, Items(r.r), Items(r.c))
end
return table.concat(lines, "\\n"), #ids, was, new
`;

const HEAD = `-- What quests give on WoW: Forever, as quest givers showed it to players of DawnTools.
-- GENERATED by tools/harvest.js from saved DawnTools data: do not edit by hand.
--   [quest] = { m = copper, x = experience, l = the level it was seen at, r = { { item, count } } given,
--               c = { { item, count } } to choose one of }
local _, DT = ...
DT.QuestRewards = {
`;

const L = lauxlib.luaL_newstate();
lualib.luaL_openlibs(L);
if (lauxlib.luaL_loadstring(L, to_luastring(MERGE)) !== 0) { console.error(to_jsstring(lua.lua_tostring(L, -1))); process.exit(1); }
lua.lua_pushstring(L, to_luastring(out.split(path.sep).join('/')));
lua.lua_pushstring(L, to_luastring(files.map(f => path.resolve(f).split(path.sep).join('/')).join('\n')));
if (lua.lua_pcall(L, 2, 4, 0) !== 0) { console.error(to_jsstring(lua.lua_tostring(L, -1))); process.exit(1); }
const body = to_jsstring(lua.lua_tostring(L, -4));
const total = lua.lua_tointeger(L, -3), was = lua.lua_tointeger(L, -2), added = lua.lua_tointeger(L, -1);
fs.writeFileSync(out, HEAD + (body ? body + '\n' : '') + '}\n');
console.log(`quests: ${was} shipped before, ${added} new, ${total} now -> ${out}`);
